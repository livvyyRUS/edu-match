  let currentTrackId = 'ege';
  let userProgress = {};

  document.addEventListener('DOMContentLoaded', () => {
    loadUserProgress();
    initTabButtons();
    renderCurrentTrack();
    updateNextDeadlineCountdown();
  });

  function loadUserProgress() {
    try {
      userProgress = JSON.parse(localStorage.getItem('edumatch_roadmap_progress') || '{}');
    } catch {
      userProgress = {};
    }
  }

  function saveUserProgress() {
    localStorage.setItem('edumatch_roadmap_progress', JSON.stringify(userProgress));
  }

  function initTabButtons() {
    const tabBtns = document.querySelectorAll('.roadmap-tab-btn');
    tabBtns.forEach(btn => {
      btn.addEventListener('click', () => {
        const trackId = btn.getAttribute('data-track');
        if (trackId && TRACKS_DATA[trackId]) {
          tabBtns.forEach(b => b.classList.remove('active'));
          btn.classList.add('active');
          currentTrackId = trackId;
          renderCurrentTrack();
        }
      });
    });
  }

  function renderCurrentTrack() {
    const track = TRACKS_DATA[currentTrackId];
    if (!track) return;

    // 1. Overview header
    const titleEl = document.getElementById('trackTitle');
    const badgeEl = document.getElementById('trackBadge');
    const descEl = document.getElementById('trackDesc');
    const statsGrid = document.getElementById('trackStatsGrid');

    if (titleEl) titleEl.textContent = track.title;
    if (badgeEl) badgeEl.textContent = track.badge;
    if (descEl) descEl.textContent = track.desc;

    if (statsGrid) {
      statsGrid.innerHTML = track.stats.map(s => `
        <div class="stat-card" style="padding: 16px;">
          <div class="stat-title">${s.label}</div>
          <div style="font-size: 16px; font-weight: 800; color: var(--text); margin-top: 4px;">${s.val}</div>
        </div>
      `).join('');
    }

    // 2. Timeline stages
    const timelineContainer = document.getElementById('timelineContainer');
    if (timelineContainer) {
      timelineContainer.innerHTML = track.stages.map(st => {
        const isCompleted = userProgress[st.id] === true;
        const checkItemsHtml = st.checklist.map((item, idx) => {
          const itemKey = `${st.id}_check_${idx}`;
          const isItemDone = userProgress[itemKey] === true;
          return `
            <label class="check-item">
              <input type="checkbox" data-key="${itemKey}" ${isItemDone ? 'checked' : ''} onchange="window.handleRoadmapCheck('${itemKey}', this.checked)">
              <span>${item}</span>
            </label>
          `;
        }).join('');

        return `
          <div class="stage-card ${isCompleted ? 'completed' : ''}" id="stage_card_${st.id}">
            <div class="stage-icon-badge">${st.number}</div>

            <div class="stage-header">
              <h3 class="stage-title">${st.title}</h3>
              <span class="stage-date-pill">${st.date}</span>
            </div>

            <p class="stage-desc">${st.desc}</p>

            <div class="checklist">
              <div style="font-size: 12px; font-weight: 700; text-transform: uppercase; color: var(--muted); margin-bottom: 4px;">Чеклист этапа:</div>
              ${checkItemsHtml}
            </div>

            <div class="protip-box">
              <strong>Совет эксперта:</strong> ${st.protip}
            </div>
          </div>
        `;
      }).join('');
    }

    updateTrackProgress();
  }

  function updateTrackProgress() {
    const track = TRACKS_DATA[currentTrackId];
    if (!track) return;

    let totalTasks = 0;
    let completedTasks = 0;

    track.stages.forEach(st => {
      st.checklist.forEach((_, idx) => {
        totalTasks++;
        const itemKey = `${st.id}_check_${idx}`;
        if (userProgress[itemKey] === true) {
          completedTasks++;
        }
      });
    });

    const percent = totalTasks > 0 ? Math.round((completedTasks / totalTasks) * 100) : 0;
    const progressFill = document.getElementById('trackProgressFill');
    const progressText = document.getElementById('trackProgressText');

    if (progressFill) progressFill.style.width = `${percent}%`;
    if (progressText) progressText.textContent = `Выполнено задач: ${completedTasks} из ${totalTasks} (${percent}%)`;
  }

  window.handleRoadmapCheck = function(key, isChecked) {
    userProgress[key] = isChecked;
    saveUserProgress();
    updateTrackProgress();
  };

  function updateNextDeadlineCountdown() {
    const countdownEl = document.getElementById('deadlineCountdown');
    if (!countdownEl) return;

    // Key milestone: June 20, 2027 (Start of admissions)
    const targetDate = new Date('2027-06-20T09:00:00+03:00');
    const now = new Date();
    const diff = targetDate - now;

    if (diff > 0) {
      const days = Math.floor(diff / (1000 * 60 * 60 * 24));
      countdownEl.textContent = `До старта приёма 2027 осталось: ${days} дн.`;
    } else {
      countdownEl.textContent = 'Приёмная кампания 2027 в самом разгаре!';
    }
  }
